"""Synthetic rehearsal of the exact local closed-archive sealer."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import zipfile
from unittest.mock import patch

import seal_closed_history_zip as helper


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('custody',type=Path)
    parser.add_argument('tool_dir',type=Path)
    args=parser.parse_args()
    plan=json.loads((args.custody/'custody-readback.private.json').read_bytes())
    image_mount=Path(plan['capture_staging']).parent
    assert os.path.ismount(image_mount)
    sealer=Path(__file__).with_name('seal_closed_history_zip.py')
    age=(args.tool_dir/'age').resolve(strict=True)
    keygen=(args.tool_dir/'age-keygen').resolve(strict=True)
    os.umask(0o077)
    with tempfile.TemporaryDirectory(prefix='synthetic-seal-',dir=image_mount) as name, tempfile.TemporaryDirectory(
        prefix='synthetic-local-key-',dir=args.custody.parent
    ) as separate:
        capture=Path(name).resolve()
        config=Path(separate).resolve()
        identity=config/'test-only.agekey'
        recipient=config/'test-only-recipient.txt'
        subprocess.run([str(keygen),'-pq','-o',str(identity)],check=True,capture_output=True,timeout=20)
        subprocess.run([str(keygen),'-y','-o',str(recipient),str(identity)],check=True,capture_output=True,timeout=20)
        dummy=capture/('1'*32+'.zip')
        with zipfile.ZipFile(dummy,'x') as archive:
            archive.writestr('example.txt',b'generated bytes for test only')
        expected=dict(status='local_custody_verified', bytes=dummy.stat().st_size,
                        sha256=digest(dummy), opaque_copy=dummy.name)
        source_receipt=capture/'source.private.json'
        source_receipt.write_text(json.dumps(expected))
        simulated=dict(capture_staging=str(capture),capture_image=plan['capture_image'],
            recipient_public_path=str(recipient),recipient_public_sha256=digest(recipient))
        (config/'custody-readback.private.json').write_text(json.dumps(simulated))
        command = [sys.executable, '-O', str(sealer), str(dummy), str(source_receipt),
                   str(config), str(age), digest(age)]
        for bad_receipt in ({**expected, 'opaque_copy': '2'*32+'.zip'},
                            {**expected, 'sha256': '0'*64}):
            source_receipt.write_text(json.dumps(bad_receipt))
            failure = subprocess.run(command, capture_output=True, timeout=35)
            assert failure.returncode != 0 and not list(capture.glob('import-*'))
        quarantines = list(capture.glob('.quarantine-*'))
        assert len(quarantines) == 1 and list(quarantines[0].glob('*.age'))
        assert not list(quarantines[0].glob('*.transfer.private.json'))
        source_receipt.write_text(json.dumps(expected))
        recipient_data = recipient.read_bytes()
        recipient.write_bytes(recipient_data + b'# modified recipient bytes\n')
        assert subprocess.run(command, capture_output=True, timeout=35).returncode != 0
        assert not list(capture.glob('import-*'))
        recipient.write_bytes(recipient_data)

        real_sync = helper.sync_directory
        def fail_after_rename(path):
            if list(capture.glob('import-*')):
                raise OSError('injected completion sync failure')
            real_sync(path)
        with patch.object(helper, 'sync_directory', fail_after_rename):
            try:
                helper.complete_import(capture, dummy, age, recipient_data.decode().strip(),
                                       digest(recipient), expected['bytes'], expected['sha256'], 2**20)
            except OSError as error:
                assert str(error) == 'injected completion sync failure'
            else:
                raise AssertionError('injected sync failure was ignored')
        assert not list(capture.glob('import-*'))
        assert any(list(folder.glob('*.transfer.private.json'))
                   for folder in capture.glob('.quarantine-*'))

        result = subprocess.run(command, check=True, capture_output=True, text=True, timeout=35)
        assert json.loads(result.stdout)['source_unchanged']
        transfer_file,=capture.glob('import-*/*.transfer.private.json')
        transfer=json.loads(transfer_file.read_bytes())
        encrypted=transfer_file.parent/transfer['ciphertext_filename']
        assert digest(encrypted)==transfer['ciphertext_sha256'] and encrypted.stat().st_size==transfer['ciphertext_bytes']
        def open_cipher(file):
            return subprocess.check_output([str(age),'-d','-i',str(identity),str(file)],timeout=20)
        recovered=open_cipher(encrypted)
        assert hashlib.sha256(recovered).hexdigest()==expected['sha256'] and len(recovered)==expected['bytes']
        manifest,=transfer_file.parent.glob('*.manifest.age')
        decoded=json.loads(open_cipher(manifest))
        assert decoded['plaintext_sha256']==expected['sha256'] and decoded['plaintext_bytes']==expected['bytes']
        assert all(t not in transfer for t in ('plaintext_sha256','plaintext_bytes'))
        assert digest(dummy)==expected['sha256']
    print(json.dumps(dict(sealer_sha256=digest(sealer),age_sha256=digest(age),synthetic_only=True,
        optimized_cli_guards=True, receipt_name_and_stream_failures_quarantined=True,
        modified_recipient_rejected=True, completion_sync_failure_quarantined=True, mounted_encrypted_capture_verified=True,exact_age_round_trip=True,encrypted_raw_manifest_verified=True,
        separate_transfer_descriptor_contains_only_ciphertext_pins=True,source_unchanged=True,network_transfer=False)))


if __name__=='__main__':
    main()
